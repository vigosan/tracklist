def detect(environ):
    for name in ("LC_ALL", "LC_MESSAGES", "LANG"):
        if environ.get(name):
            return "es" if environ[name].startswith("es") else "en"
    return "en"


LANGUAGE = detect(os.environ)


def t(key, **values):
    return MESSAGES[LANGUAGE][key].format(**values)
